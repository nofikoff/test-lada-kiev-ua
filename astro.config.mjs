// @ts-check
import { defineConfig, fontProviders } from 'astro/config';
import sitemap from '@astrojs/sitemap';

// Канонический хост — с www: apex отвечает постоянным перенаправлением (docs/specs/routes.md §Канонический хост).
// Единственное объявление домена в коде сайта: src/i18n/paths.ts читает его как import.meta.env.SITE.
const SITE = 'https://www.lada.kiev.ua';

/**
 * Свой порт у preview, а не общий с dev 4321: иначе e2e (reuseExistingServer) и Lighthouse
 * молча уходят на запущенный astro dev и проверяют не dist/. Отсюда же его берёт playwright.config.ts.
 */
export const PREVIEW_PORT = 4329;

/**
 * Начертания перечислены те, что действительно встречаются в разметке, а не весь набор
 * действующей ссылки на сторонний домен: каждое лишнее — отдельный файл в загрузке.
 *
 * Inter: 300 — текст страницы и лид, 400 — названия позиций прайса и цены, 500 — надзаголовки,
 * кнопки и вкладки. Начертания 600 больше нет: крупные акценты ушли в антикву целиком,
 * и лишний файл в загрузке остался бы ради ни одного употребления.
 * Cormorant: 300 — заголовок первого экрана и заголовки секций, 400 — подзаголовки и заголовки
 * групп прайса, 500 — монограмма; курсив — подзаголовок первого экрана и закрывающая строка
 * «Про нас» (ADR-014).
 *
 * Подмножество `cyrillic` обязательно: две локали из трёх — кириллица, и без него украинский
 * заголовок отрисовывается запасным шрифтом (ADR-009).
 */
const SUBSETS = /** @type {['latin', 'cyrillic']} */ (['latin', 'cyrillic']);

/**
 * Tailwind подключён через postcss.config.js, а не через @astrojs/tailwind.
 * Интеграция объявляет peer-диапазон astro ^3||^4||^5 и с седьмой версией не ставится;
 * её работа — регистрация того же плагина PostCSS, который Vite подхватывает сам.
 * Обоснование выбора третьей версии Tailwind, а не четвёртой — ADR-010.
 */
export default defineConfig({
  site: SITE,
  server: ({ command }) => (command === 'preview' ? { port: PREVIEW_PORT } : {}),
  output: 'static',
  // Совпадение двух адресов и совпадение идентификаторов в прайсе обязаны ронять сборку,
  // а не писать предупреждение: по умолчанию побеждает запись с большим приоритетом,
  // то есть одна из двух цен исчезает молча. Ровно этот класс ошибок здесь недопустим.
  prerenderConflictBehavior: 'error',
  build: {
    // Даёт ru/index.html: адрес /ru/ обслуживается напрямую, /ru приходит на него
    // перенаправлением Apache. Форма 'file' перенесла бы корректность адресов в конфигурацию сервера.
    format: 'directory',
  },
  i18n: {
    defaultLocale: 'uk',
    locales: ['uk', 'ru', 'en'],
    routing: {
      // Основной язык живёт на корне без префикса — действующая схема адресов, менять её нельзя.
      prefixDefaultLocale: false,
    },
  },
  /**
   * Шрифты скачиваются на сборке и отдаются с собственного домена: два сторонних домена
   * уходят из критического пути загрузки, а ссылки предзагрузки и метрики запасного шрифта
   * Astro строит сам (ADR-009).
   */
  fonts: [
    {
      provider: fontProviders.google(),
      name: 'Inter',
      cssVariable: '--font-inter',
      weights: [300, 400, 500],
      styles: ['normal'],
      subsets: SUBSETS,
      fallbacks: ['system-ui', 'sans-serif'],
    },
    // `weights` и `styles` перемножаются, поэтому объявить курсив только для 300 и 400
    // (ADR-014) конфигурацией нельзя: заявленным оказывается и курсив 500. Лишним
    // он остаётся только в объявлении — @font-face без единого употребления браузер
    // не загружает, а из предзагрузки курсив отобран в BaseLayout.astro.
    {
      provider: fontProviders.google(),
      name: 'Cormorant',
      cssVariable: '--font-cormorant',
      weights: [300, 400, 500],
      styles: ['normal', 'italic'],
      subsets: SUBSETS,
      fallbacks: ['Georgia', 'serif'],
    },
  ],
  /**
   * Сжатие стилей переведено с lightningcss на esbuild из-за одной правки, которую первый
   * складывает неверно: `animation: reveal linear both` рядом с `animation-timeline: view()`
   * он сворачивает в `animation: linear both reveal view()`. Сокращённая запись таймлайна
   * в браузерах не принята (`CSS.supports('animation','linear both reveal view()')` → false
   * в Chrome 153 и в WebKit), поэтому правило отбрасывается целиком: проявление блоков,
   * уплотнение шапки и всё, что стоит на таймлайне, молча не работает.
   *
   * Глазами это не ловится — на прогоне блоки видны, потому что видимость и есть исходное
   * состояние (docs/specs/motion.md правило 3), — и проверкой вложенности в
   * reduced-motion.spec.ts тоже: вложенность правил при этом верна. Ловит это соседняя проверка
   * там же, на сокращённую запись. esbuild оставляет обе записи раздельными.
   */
  vite: {
    build: {
      cssMinify: 'esbuild',
    },
  },
  integrations: [
    sitemap({
      i18n: {
        defaultLocale: 'uk',
        // Полные теги языка: карта сайта объявляет регион, разметка страницы — только язык.
        locales: { uk: 'uk-UA', ru: 'ru-UA', en: 'en' },
      },
    }),
  ],
});
